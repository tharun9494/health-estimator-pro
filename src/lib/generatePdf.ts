import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { Feature } from "@/data/categories";
import { ClientInfo } from "@/components/ClientForm";

const fmt = (n: number) => "₹" + Math.round(n).toLocaleString("en-IN");

export function generateQuotePdf(
  selected: Set<string>,
  margin: number,
  client: ClientInfo,
  categoryName: string,
  allFeatures: Feature[]
) {
  const items = allFeatures.filter((f) => selected.has(f.id));
  const minBase = items.reduce((s, f) => s + f.price, 0);
  const maxBase = items.reduce((s, f) => s + f.totalCost, 0);
  const days = Math.max(15, items.reduce((s, f) => s + f.days, 0));
  const minMargin = minBase * (margin / 100);
  const maxMargin = maxBase * (margin / 100);
  const minTotal = minBase + minMargin;
  const maxTotal = maxBase + maxMargin;
  const today = new Date().toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });

  const doc = new jsPDF();
  const w = doc.internal.pageSize.getWidth();

  // Header bar
  doc.setFillColor(30, 64, 175); // blue-800
  doc.rect(0, 0, w, 38, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22);
  doc.setFont("helvetica", "bold");
  doc.text("BuildQuote", 14, 18);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text("Professional Cost Estimator", 14, 26);
  doc.setFontSize(9);
  doc.text(today, w - 14, 18, { align: "right" });
  doc.text("Quote #BQ-" + Date.now().toString().slice(-6), w - 14, 26, { align: "right" });

  // Category title
  let y = 48;
  doc.setTextColor(30, 64, 175);
  doc.setFontSize(16);
  doc.setFont("helvetica", "bold");
  doc.text(categoryName, 14, y);

  // Client info
  y += 12;
  doc.setTextColor(60, 60, 60);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  if (client.name) { doc.text(`Client: ${client.name}`, 14, y); y += 6; }
  if (client.business) { doc.text(`Business: ${client.business}`, 14, y); y += 6; }
  if (client.phone) { doc.text(`Phone: ${client.phone}`, 14, y); y += 6; }

  // Divider
  y += 4;
  doc.setDrawColor(200, 200, 200);
  doc.line(14, y, w - 14, y);
  y += 8;

  // Features table
  doc.setTextColor(30, 64, 175);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Selected Features", 14, y);
  y += 4;

  const tableBody = items.map((f, i) => [
    (i + 1).toString(),
    f.name,
    f.description.length > 50 ? f.description.slice(0, 47) + "..." : f.description,
    fmt(f.price),
    fmt(f.totalCost),
    `${f.days} days`,
  ]);

  autoTable(doc, {
    startY: y,
    head: [["#", "Feature", "Description", "Price", "Total Cost", "Timeline"]],
    body: tableBody,
    margin: { left: 14, right: 14 },
    headStyles: {
      fillColor: [30, 64, 175],
      textColor: 255,
      fontStyle: "bold",
      fontSize: 9,
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [50, 50, 50],
    },
    alternateRowStyles: { fillColor: [240, 245, 255] },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: 35 },
      2: { cellWidth: 55 },
      3: { halign: "right" },
      4: { halign: "right" },
      5: { halign: "center" },
    },
  });

  // Summary section
  y = (doc as any).lastAutoTable.finalY + 12;

  // Check if we need a new page
  if (y > doc.internal.pageSize.getHeight() - 80) {
    doc.addPage();
    y = 20;
  }

  // Summary box
  const boxX = 14;
  const boxW = w - 28;

  doc.setFillColor(240, 245, 255);
  doc.setDrawColor(30, 64, 175);
  doc.roundedRect(boxX, y, boxW, 58, 3, 3, "FD");

  y += 10;
  doc.setTextColor(30, 64, 175);
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.text("Cost Summary", boxX + 8, y);

  y += 10;
  doc.setTextColor(60, 60, 60);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`Base Cost:`, boxX + 8, y);
  doc.text(`${fmt(minBase)} – ${fmt(maxBase)}`, boxX + boxW - 8, y, { align: "right" });

  y += 8;
  doc.text(`Safety Margin (${margin}%):`, boxX + 8, y);
  doc.text(`${fmt(minMargin)} – ${fmt(maxMargin)}`, boxX + boxW - 8, y, { align: "right" });

  y += 3;
  doc.setDrawColor(180, 180, 220);
  doc.line(boxX + 8, y, boxX + boxW - 8, y);

  y += 8;
  doc.setTextColor(30, 64, 175);
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.text(`Estimated Total:`, boxX + 8, y);
  doc.text(`${fmt(minTotal)} – ${fmt(maxTotal)}`, boxX + boxW - 8, y, { align: "right" });

  y += 10;
  doc.setFontSize(10);
  doc.setTextColor(80, 80, 80);
  doc.setFont("helvetica", "normal");
  doc.text(`Estimated Timeline: ${days}–${days + 10} days`, boxX + 8, y);

  // Footer
  const pageH = doc.internal.pageSize.getHeight();
  doc.setDrawColor(200, 200, 200);
  doc.line(14, pageH - 18, w - 14, pageH - 18);
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text("Generated by BuildQuote Estimator • This is an estimate, not a final invoice.", 14, pageH - 12);
  doc.text("Prices may vary based on project requirements.", 14, pageH - 7);

  // Download
  const fileName = `Quote_${categoryName.replace(/\s+/g, "_")}_${today.replace(/\s+/g, "")}.pdf`;
  doc.save(fileName);
}
