import { Button } from "@/components/ui/button";
import { Feature } from "@/data/categories";
import { ClientInfo } from "./ClientForm";
import { FileText, MessageCircle } from "lucide-react";

interface QuoteActionsProps {
  selected: Set<string>;
  margin: number;
  client: ClientInfo;
  categoryName: string;
  allFeatures: Feature[];
}

const fmt = (n: number) => "₹" + Math.round(n).toLocaleString("en-IN");

const buildSummary = (selected: Set<string>, margin: number, client: ClientInfo, categoryName: string, allFeatures: Feature[]) => {
  const items = allFeatures.filter((f) => selected.has(f.id));
  const minBase = items.reduce((s, f) => s + f.minPrice, 0);
  const maxBase = items.reduce((s, f) => s + f.maxPrice, 0);
  const days = Math.max(15, items.reduce((s, f) => s + f.days, 0));
  const minTotal = minBase * (1 + margin / 100);
  const maxTotal = maxBase * (1 + margin / 100);

  let text = `*${categoryName} — Quote*\n\n`;
  if (client.name) text += `*Client:* ${client.name}\n`;
  if (client.business) text += `*Business:* ${client.business}\n`;
  if (client.phone) text += `*Phone:* ${client.phone}\n`;
  text += `\n*Selected Features:*\n`;
  items.forEach((f) => { text += `✅ ${f.name} (${fmt(f.minPrice)}–${fmt(f.maxPrice)})\n`; });
  text += `\n*Base Cost:* ${fmt(minBase)} – ${fmt(maxBase)}`;
  text += `\n*Safety Margin (${margin}%):* ${fmt(minBase * margin / 100)} – ${fmt(maxBase * margin / 100)}`;
  text += `\n\n💰 *Estimated Total: ${fmt(minTotal)} – ${fmt(maxTotal)}*`;
  text += `\n🕐 *Timeline: ${days}–${days + 10} days*`;
  text += `\n\n_Generated by BuildQuote Estimator_`;
  return text;
};

const QuoteActions = ({ selected, margin, client, categoryName, allFeatures }: QuoteActionsProps) => {
  const items = allFeatures.filter((f) => selected.has(f.id));

  const handleWhatsApp = () => {
    const text = buildSummary(selected, margin, client, categoryName, allFeatures);
    window.open(`https://wa.me/?text=${encodeURIComponent(text)}`, "_blank");
  };

  const handleCopy = () => {
    const text = buildSummary(selected, margin, client, categoryName, allFeatures);
    navigator.clipboard.writeText(text);
  };

  return (
    <div className="flex flex-col gap-2">
      <Button onClick={handleCopy} disabled={items.length === 0} className="w-full gradient-primary text-primary-foreground shadow-primary hover:opacity-90">
        <FileText className="w-4 h-4 mr-2" /> Copy Quote Summary
      </Button>
      <Button onClick={handleWhatsApp} disabled={items.length === 0} variant="outline" className="w-full border-success text-success hover:bg-success/5">
        <MessageCircle className="w-4 h-4 mr-2" /> Share via WhatsApp
      </Button>
    </div>
  );
};

export default QuoteActions;
